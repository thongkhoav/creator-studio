create table if not exists public.brainstorm_history (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  brief text not null,
  format text not null default 'Vlog ngắn',
  duration text not null default '30-40 giây',
  source text not null default 'ai' check (source in ('ai', 'demo')),
  platforms jsonb not null default '[]'::jsonb,
  ideas jsonb not null default '[]'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.brainstorm_history
  add column if not exists source text not null default 'ai';

create index if not exists brainstorm_history_workspace_created_idx
  on public.brainstorm_history (workspace_id, created_at desc, id desc);

alter table public.brainstorm_history enable row level security;
drop policy if exists "members can access brainstorm history" on public.brainstorm_history;
create policy "members can access brainstorm history"
  on public.brainstorm_history for all
  using (public.is_workspace_member(workspace_id))
  with check (public.is_workspace_member(workspace_id));
