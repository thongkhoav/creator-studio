-- Workspace-owned concept library.
-- Concepts are shared by members of one workspace and independent from ideas.
create table if not exists public.workspace_concepts (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null,
  normalized_name text generated always as (lower(btrim(name))) stored,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint workspace_concepts_name_length
    check (char_length(btrim(name)) between 1 and 80)
);
alter table public.workspace_concepts
  add column if not exists normalized_name text
  generated always as (lower(btrim(name))) stored;

create unique index if not exists workspace_concepts_workspace_name_ci_idx
  on public.workspace_concepts (workspace_id, normalized_name);
create index if not exists workspace_concepts_workspace_idx
  on public.workspace_concepts (workspace_id, created_at, id);

alter table public.workspace_concepts enable row level security;

drop policy if exists "members can access workspace concepts"
  on public.workspace_concepts;
create policy "members can access workspace concepts"
  on public.workspace_concepts for all
  using (public.is_workspace_member(workspace_id))
  with check (public.is_workspace_member(workspace_id));
