-- Multi-user workspaces. Supabase Auth owns identities; application rows are scoped by workspace.
create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);
create table if not exists public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('owner','admin','editor','viewer')),
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);
create or replace function public.is_workspace_member(target_workspace uuid)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.workspace_members where workspace_id = target_workspace and user_id = auth.uid()) $$;
create or replace function public.workspace_role(target_workspace uuid)
returns text language sql stable security definer set search_path = public
as $$ select role from public.workspace_members where workspace_id = target_workspace and user_id = auth.uid() limit 1 $$;

create table if not exists public.content_variants (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  idea_id bigint not null references public.ideas(id) on delete cascade,
  platform text not null,
  title text not null default '', hook text not null default '', caption text not null default '',
  duration_seconds integer, status text not null default 'draft' check (status in ('draft','ready','published')),
  created_by uuid references auth.users(id), created_at timestamptz not null default now(),
  unique (idea_id, platform)
);
create table if not exists public.content_schedules (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  variant_id bigint not null references public.content_variants(id) on delete cascade,
  scheduled_at timestamptz not null, status text not null default 'scheduled' check (status in ('draft','scheduled','published','cancelled')),
  published_url text not null default '', assigned_to uuid references auth.users(id), created_by uuid references auth.users(id), created_at timestamptz not null default now()
);
create table if not exists public.platform_presets (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  platform text not null, canvas text not null default '1080 x 1920', safe_zone text not null default '', caption_guidance text not null default '', duration_guidance text not null default '', created_at timestamptz not null default now(), unique(workspace_id, platform)
);
create table if not exists public.publishing_checklist_items (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  variant_id bigint not null references public.content_variants(id) on delete cascade,
  label text not null, completed boolean not null default false, completed_by uuid references auth.users(id), completed_at timestamptz, sort_order smallint not null default 0
);
create table if not exists public.media_assets (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  idea_id bigint references public.ideas(id) on delete cascade,
  variant_id bigint references public.content_variants(id) on delete cascade,
  kind text not null check (kind in ('final_video','thumbnail','raw_footage','project','audio','published')), label text not null default '', url text not null, created_by uuid references auth.users(id), created_at timestamptz not null default now()
);

alter table public.workspaces enable row level security;
alter table public.workspace_members enable row level security;
alter table public.content_variants enable row level security;
alter table public.content_schedules enable row level security;
alter table public.platform_presets enable row level security;
alter table public.publishing_checklist_items enable row level security;
alter table public.media_assets enable row level security;
create policy "workspace members can read workspaces" on public.workspaces for select using (public.is_workspace_member(id));
create policy "members can read memberships" on public.workspace_members for select using (public.is_workspace_member(workspace_id));
create policy "members can access variants" on public.content_variants using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
create policy "members can access schedules" on public.content_schedules using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
create policy "members can access presets" on public.platform_presets using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
create policy "members can access checklist" on public.publishing_checklist_items using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));
create policy "members can access media" on public.media_assets using (public.is_workspace_member(workspace_id)) with check (public.is_workspace_member(workspace_id));

create or replace function public.create_workspace(workspace_name text)
returns public.workspaces
language plpgsql security definer set search_path = public
as $$
declare created public.workspaces;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  insert into public.workspaces(name, created_by) values (trim(workspace_name), auth.uid()) returning * into created;
  insert into public.workspace_members(workspace_id, user_id, role) values (created.id, auth.uid(), 'owner');
  return created;
end;
$$;
revoke all on function public.create_workspace(text) from public, anon;
grant execute on function public.create_workspace(text) to authenticated;
