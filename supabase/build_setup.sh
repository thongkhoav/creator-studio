#!/bin/sh
# Rebuild setup.sql (one paste for the SQL Editor) from the migrations folder.
cd "$(dirname "$0")"
{
  printf -- '-- Full schema for a new Supabase project: paste into the SQL Editor and run once.\n'
  printf -- '-- Generated by supabase/build_setup.sh from supabase/migrations. Do not edit by hand.\n\n'
  for f in migrations/*.sql; do printf -- '-- ==== %s\n' "$f"; cat "$f"; printf '\n'; done
} > setup.sql
